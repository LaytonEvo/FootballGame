import type { EconomyConfig } from '@ff/shared';
import type { RuleSet } from '../rules.js';
import type { EconomyRow } from './economy.js';
import type { ReplayData, ScenarioSummary } from './sim.js';

export interface ReportInput {
  rules: RuleSet;
  eco: EconomyConfig;
  data: ReplayData;
  summaries: ScenarioSummary[];
  rows: EconomyRow[];
  seasons: number;
}

const f0 = (n: number) => n.toFixed(0);
const f1 = (n: number) => n.toFixed(1);
const f2 = (n: number) => n.toFixed(2);
const pc = (n: number) => `${(n * 100).toFixed(0)}%`;

/** Render docs/ECONOMY_CHECK.md. Numbers are computed; the narrative reads them, so re-runs stay honest. */
export function renderEconomyReport(i: ReportInput): string {
  const S = (label: string) => {
    const s = i.summaries.find((x) => x.label.startsWith(label));
    if (!s) throw new Error(`missing scenario ${label}`);
    return s;
  };
  const R = (label: string) => i.rows.find((x) => x.label.startsWith(label))!;
  const casualP = S('casual (auto-pick, persistent');
  const casualBoldP = S('casual + bold (persistent');
  const smartP = S('smart (persistent');
  const casualR = S('casual (auto-pick, redrawn');
  const smartR = S('smart (redrawn');
  const goalR = S('always goal');
  const chaos = S('chaos chaser');
  const bronze = S('smart, all Bronze');
  const elite = S('smart, all Elite');
  const prices = i.eco.prices_coins;
  const casualRow = R('casual (auto-pick, persistent');
  const smartRow = R('smart (persistent');
  const freeShare = 1 / casualRow.cardsPerWeekWithFreePack;
  const gws = i.data.gameweeks;

  const table = [
    '| Scenario | Season mean | p10 | p50 | p90 | Pts / GW | Landed / GW | Hit rate | Negative weeks |',
    '| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |',
    ...i.summaries.map(
      (s) =>
        `| ${s.label} | ${f1(s.mean)} | ${f0(s.p10)} | ${f0(s.p50)} | ${f0(s.p90)} | ${f2(s.perGameweek)} | ${f2(s.landedPerGameweek)} | ${pc(s.hitRate)} | ${pc(s.negativeWeekShare)} |`,
    ),
  ];
  const ms = i.eco.season_milestones;
  const eco = [
    `| Scenario | Coins / GW | GWs per player pack (${prices.player_pack}) | GWs per swap (${prices.card_swap}) | GWs per squad pack (${prices.squad_pack}) | Cards / GW from Coins | Cards / GW incl. free pack | ${ms.map((m) => `${m.season_points} pts at GW`).join(' | ')} |`,
    `| --- | ---: | ---: | ---: | ---: | ---: | ---: | ${ms.map(() => '---:').join(' | ')} |`,
    ...i.rows
      .filter((r) => !r.label.startsWith('chaos') && !r.label.startsWith('random'))
      .map(
        (r) =>
          `| ${r.label} | ${f1(r.coinsPerGameweek)} | ${f1(r.weeksPerPlayerPack)} | ${f1(r.weeksPerSwap)} | ${f1(r.weeksPerSquadPack)} | ${f2(r.coinCardsPerWeek)} | ${f2(r.cardsPerWeekWithFreePack)} | ${Object.values(
            r.milestoneGameweek,
          )
            .map((g) => g ?? '—')
            .join(' | ')} |`,
      ),
  ];

  // Proposed milestones: put the top milestone at the casual persistent-squad median season (38 GWs),
  // and space the others evenly, rounded to 50.
  const casualSeason = casualP.perGameweek * 38;
  const top = Math.round((casualSeason * 1.1) / 50) * 50;
  const proposed = [0.25, 0.5, 0.75, 1].map((f) => Math.round((top * f) / 50) * 50);

  return `# Economy check (Phase 1)

Generated by \`pnpm economy-check\` (packages/scoring/src/replay). Do not edit the numbers by hand; re-run instead.

- Scoring rules: \`config/scoring.v0.2.json\` (version ${i.rules.version}), basic feed only: ${i.rules.basicFeedOnly ? 'yes' : 'no'}.
- Economy: \`config/economy.v0.1.json\` (version ${i.eco.version}).
- Data: public 2025/26 FPL dataset snapshot (\`data/fpl-2025-26\`), gameweeks ${gws[0]}–${gws.at(-1)} (${gws.length} simulated; the first three have no "previous four gameweeks" history, as in \`tools/sim/sim.py\`).
- ${i.seasons} seeded seasons per scenario. Every gameweek is scored by the production engine (\`scoreSquad\`), so captain, bold action, rarity multipliers, the sub rule, double and blank gameweeks are all included. Re-running gives identical totals (covered by \`test/replay.test.ts\`).

## What the strategies do

- **Casual** = taps Auto-pick every week: highest-average Likely/Possible action ×2 per player, auto captain, no bold action. **Casual + bold** also marks their most likely action as bold.
- **Smart** = picks the two highest-average actions from any tier (no chaos), captains the best expected scorer, and uses the bold action only when it has positive expected value.
- **Always goal**, **chaos chaser** and **random** are the comparison strategies from the Python sim (chaos chaser also always bolds its highest-value action).
- **Persistent squad** = one random six-card squad drawn from the regular-starter pool at GW${gws[0]} and kept all season (injuries, transfers and blanks hit it, so the sub rule matters). **Redrawn** = a fresh squad of regular starters each week (the Python sim's method; an upper bound for an active player who keeps their five fresh).

## Points

${table.join('\n')}

Findings:

1. **Average points per gameweek:** casual ${f1(casualP.perGameweek)} (persistent) to ${f1(casualR.perGameweek)} (redrawn); smart ${f1(smartP.perGameweek)} to ${f1(smartR.perGameweek)}. A full 38-week season is roughly ${f0(casualP.perGameweek * 38)}–${f0(smartR.perGameweek * 38)} Season Points.
2. **Skill pays, but Auto-pick is strong.** Smart beats casual by ${pc(smartP.mean / casualP.mean - 1)} (persistent) and ${pc(smartR.mean / casualR.mean - 1)} (redrawn), and beats "always goal" by ${pc(smartR.mean / goalR.mean - 1)}. The strategies still do not read fixtures, so the real skill edge should be larger. Because Auto-pick is close to optimal on average, consider making it pick from Likely only (or randomise among the top three) if testers find it removes the decision.
3. **Captain and bold add about ${f1(casualBoldP.perGameweek - casualP.perGameweek)} points/GW for a casual player** who bolds their safest action. Smart players' bold choice is EV-positive only on high-hit-rate actions, so bold is a small, safe edge rather than a swing; the bold penalty mostly bites players who bold long shots.
4. **Chaos chasing loses** (${f1(chaos.perGameweek)} pts/GW, negative in ${pc(chaos.negativeWeekShare)} of weeks), so chaos picks and big bold punts cannot win a league. Season Points can go negative for them; Coins are floored at 0 per week in this model (the ledger never debits for a bad week).
5. **Rarity gap:** with the rarity multipliers, an all-Elite squad scores ${f2(elite.mean / bronze.mean)}× an all-Bronze one (spec target ≈1.10×). Still well below FPL's raw quality gap, but wider than the design note. If the closed test confirms it, widen the multipliers (e.g. Bronze 1.25 / Silver 1.12 / Gold 1.0 / Elite 0.85) and re-run.

## Coins and cards

Coins = 1 per point (weekly score floored at 0). The weekly free pack (one player card) is unlocked by confirming that week's actions.

${eco.join('\n')}

Is 100 / 60 / 400 "roughly one new card per week including the weekly free pack"?

- **Yes.** A casual player earns ${f1(casualRow.coinsPerGameweek)} Coins/GW: a player pack every ${f1(casualRow.weeksPerPlayerPack)} weeks, a swap every ${f1(casualRow.weeksPerSwap)} weeks, a squad pack about every ${f0(casualRow.weeksPerSquadPack)} weeks. With the free pack that is ${f2(casualRow.cardsPerWeekWithFreePack)} cards/GW (smart: ${f2(smartRow.cardsPerWeekWithFreePack)}).
- The free pack is ${pc(freeShare)} of a casual player's new cards, so **confirming actions each week is the main card source** and Coins are a top-up. That is the intended retention lever; it also means a player who misses weeks (carried-over actions do not unlock the pack) falls behind on collection but not on the leaderboard.
- The squad pack is the cheapest card per Coin (${f0(prices.squad_pack / 5)} vs ${prices.player_pack}); fine as a "save up" target, roughly twice a season.

**Recommendation on prices: keep 100 / 60 / 400 for the closed test.** No change needed.

**Milestones need adjusting.** With ${ms.map((m) => m.season_points).join(' / ')}, the average casual player reaches ${Object.values(casualRow.milestoneGameweek).filter((g) => g !== null).length} of ${ms.length} milestones in a season and the top one (${ms.at(-1)!.season_points}) only an above-average smart player with a strong squad reaches. Proposed: **${proposed.join(' / ')}** (top milestone ≈ 110% of a casual 38-week season), so a regular casual player sees three or four rewards spread across the season.

## Caveats

- Hit rates in the config come from the same 2025/26 data, so "smart" has hindsight about average rates (but not about individual matches).
- Basic feed only; advanced-feed actions (tackles, CBI, defensive contribution) are excluded, which is why totals differ from the Python baseline (\`tools/sim/baseline/summary.json\`, which included them and had no bold action or rarity multipliers).
- Squads ignore the two-per-club limit and the squad rating cap; card upgrades over the season are not modelled.
`;
}
