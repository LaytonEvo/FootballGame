import { and, asc, eq, gte, inArray, isNotNull, isNull, lte } from 'drizzle-orm';
import type { AppContext } from '../context.js';
import { DAY, HOUR, MINUTE } from '../clock.js';
import type { DbOrTx } from '../db/client.js';
import { gameweeks, notifications, selections, squadSlots, users } from '../db/schema.js';
import { newId } from '../ids.js';
import { track } from './analytics.js';

export const NOTIFICATION_KINDS = {
  deadline_reminder: true,
  actions_carried_over: true,
  action_landed: true,
  league_overtaken: false,
  recap_ready: true,
  card_changed: true,
  new_pack: true,
  trade: true,
} as const;
export type NotificationKind = keyof typeof NOTIFICATION_KINDS;

/** Landed alerts wait this long so several landing together go out as one push. */
export const LANDED_BATCH_MS = MINUTE;

export function prefEnabled(prefs: unknown, kind: NotificationKind): boolean {
  const p = (prefs ?? {}) as Partial<Record<NotificationKind, boolean>>;
  return p[kind] ?? NOTIFICATION_KINDS[kind];
}

export interface NotifyInput {
  userId: string;
  kind: NotificationKind;
  title: string;
  body: string;
  data?: Record<string, unknown>;
  dedupeKey: string;
  sendAfter?: Date;
}

/** Queue a notification. Idempotent on dedupeKey. Respects the user's switches (kept as suppressed for audit). */
export async function notify(db: DbOrTx, now: Date, n: NotifyInput) {
  const [u] = await db.select({ prefs: users.notificationPrefs }).from(users).where(eq(users.id, n.userId));
  const off = !prefEnabled(u?.prefs, n.kind);
  await db
    .insert(notifications)
    .values({
      id: newId(),
      userId: n.userId,
      kind: n.kind,
      title: n.title,
      body: n.body,
      data: n.data ?? {},
      dedupeKey: n.dedupeKey,
      createdAt: now,
      sendAfter: n.sendAfter ?? now,
      suppressed: off ? 'pref_off' : null,
      sentAt: off ? now : null,
    })
    .onConflictDoNothing({ target: notifications.dedupeKey });
}

/**
 * Deadline reminders 24h and 2h before the deadline, only for players with a squad who have not confirmed.
 * Generated by the tick inside each window, so a late tick never sends a stale reminder.
 */
export async function queueDeadlineReminders(ctx: AppContext) {
  const now = ctx.clock.now();
  const upcoming = await ctx.db
    .select()
    .from(gameweeks)
    .where(
      and(
        eq(gameweeks.status, 'upcoming'),
        gte(gameweeks.deadlineAt, now),
        lte(gameweeks.deadlineAt, new Date(now.getTime() + DAY)),
      ),
    );
  let queued = 0;
  for (const gw of upcoming) {
    const left = gw.deadlineAt.getTime() - now.getTime();
    const which = left <= 2 * HOUR ? '2h' : left <= 24 * HOUR && left > 2 * HOUR ? '24h' : null;
    if (!which) continue;
    const withSquad = [
      ...new Set((await ctx.db.select({ u: squadSlots.userId }).from(squadSlots)).map((r) => r.u)),
    ];
    const confirmed = new Set(
      (
        await ctx.db
          .select({ u: selections.userId })
          .from(selections)
          .where(and(eq(selections.gameweekId, gw.id), isNotNull(selections.confirmedAt)))
      ).map((r) => r.u),
    );
    for (const userId of withSquad.filter((u) => !confirmed.has(u))) {
      await notify(ctx.db, now, {
        userId,
        kind: 'deadline_reminder',
        title: which === '2h' ? `GW${gw.number} locks in 2 hours` : `GW${gw.number} locks tomorrow`,
        body: 'Pick your actions. Same as last week takes one tap.',
        data: { route: '/picks', gameweekId: gw.id },
        dedupeKey: `deadline${which}:${gw.id}:${userId}`,
      });
      queued += 1;
    }
  }
  return queued;
}

const NEW_PACK_DAILY_CAP = 1;

/**
 * Send everything due. Action-landed alerts for a user are merged into one push. New-pack pushes are capped at
 * one a day (extra ones are marked suppressed, the packs themselves are unaffected).
 */
export async function deliverNotifications(ctx: AppContext) {
  const now = ctx.clock.now();
  const due = await ctx.db
    .select({ n: notifications, token: users.pushToken })
    .from(notifications)
    .innerJoin(users, eq(users.id, notifications.userId))
    .where(and(isNull(notifications.sentAt), lte(notifications.sendAfter, now)))
    .orderBy(asc(notifications.createdAt));
  const messages: {
    ids: string[];
    userId: string;
    kind: string;
    token: string | null;
    title: string;
    body: string;
    data: Record<string, unknown>;
  }[] = [];
  const landedByUser = new Map<string, typeof due>();
  for (const row of due) {
    if (row.n.kind === 'action_landed') {
      landedByUser.set(row.n.userId, [...(landedByUser.get(row.n.userId) ?? []), row]);
      continue;
    }
    if (row.n.kind === 'new_pack') {
      const recent = await ctx.db
        .select({ id: notifications.id })
        .from(notifications)
        .where(
          and(
            eq(notifications.userId, row.n.userId),
            eq(notifications.kind, 'new_pack'),
            isNull(notifications.suppressed),
            gte(notifications.sentAt, new Date(now.getTime() - DAY)),
          ),
        );
      const alreadyThisRun = messages.filter(
        (m) => m.userId === row.n.userId && m.kind === 'new_pack',
      ).length;
      if (recent.length + alreadyThisRun >= NEW_PACK_DAILY_CAP) {
        await ctx.db
          .update(notifications)
          .set({ sentAt: now, suppressed: 'daily_cap' })
          .where(eq(notifications.id, row.n.id));
        continue;
      }
    }
    messages.push({
      ids: [row.n.id],
      userId: row.n.userId,
      kind: row.n.kind,
      token: row.token,
      title: row.n.title,
      body: row.n.body,
      data: row.n.data as Record<string, unknown>,
    });
  }
  for (const [userId, rows] of landedByUser) {
    const pts = rows.reduce((s, r) => s + Number((r.n.data as { points?: number }).points ?? 0), 0);
    messages.push({
      ids: rows.map((r) => r.n.id),
      userId,
      kind: 'action_landed',
      token: rows[0]!.token,
      title: rows.length === 1 ? rows[0]!.n.title : `${rows.length} actions landed · +${pts}`,
      body: rows.map((r) => r.n.body).join(' · '),
      data: { route: '/', count: rows.length },
    });
  }
  const sendable = messages.filter((m) => m.token);
  if (sendable.length)
    await ctx.push.send(
      sendable.map((m) => ({ token: m.token!, title: m.title, body: m.body, data: m.data })),
    );
  for (const m of messages) {
    await ctx.db
      .update(notifications)
      .set({ sentAt: now, suppressed: m.token ? null : 'no_push_token' })
      .where(inArray(notifications.id, m.ids));
    if (m.token)
      await track(ctx.db, now, m.userId, 'notification_sent', { kind: m.kind, merged: m.ids.length });
  }
  return messages;
}
